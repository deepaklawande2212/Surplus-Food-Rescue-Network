ALTER SESSION SET NLS_DATE_FORMAT = 'YYYY-MM-DD HH24:MI:SS';

-- =====================================================================
--  PART A: OPERATIONAL QUERIES (DAY-TO-DAY USE)
-- =====================================================================

-- Q1. WHAT FOOD IS AVAILABLE RIGHT NOW, AND WHERE?
SELECT B.BATCH_ID, B.TITLE, D.ORG_NAME AS DONOR, Z.ZONE_NAME,
       B.QUANTITY_MEALS, B.EXPIRY_TIME
FROM   FOOD_BATCHES B
       JOIN DONORS D ON D.DONOR_ID = B.DONOR_ID
       JOIN ZONES  Z ON Z.ZONE_ID  = D.ZONE_ID
WHERE  B.STATUS = 'AVAILABLE'
  AND  B.EXPIRY_TIME > SYSDATE
ORDER BY B.EXPIRY_TIME;

-- Q2. WHICH FOOD IS ABOUT TO EXPIRE? (USES VIEW 1)
SELECT * FROM V_EXPIRING_SOON_BATCHES ORDER BY MINUTES_LEFT;

-- Q3. WHICH NGOS CAN TAKE BATCH 7? (SAME ZONE, VERIFIED, VEG RULE, ENOUGH CAPACITY)
SELECT N.NGO_ID, N.ORG_NAME, N.DAILY_CAPACITY_MEALS
FROM   FOOD_BATCHES B
       JOIN DONORS D ON D.DONOR_ID = B.DONOR_ID
       JOIN NGOS   N ON N.ZONE_ID  = D.ZONE_ID
WHERE  B.BATCH_ID = 7
  AND  N.VERIFICATION_STATUS = 'VERIFIED'
  AND  (B.IS_VEG = 1 OR N.ACCEPTS_VEG_ONLY = 0)
  AND  N.DAILY_CAPACITY_MEALS >= B.QUANTITY_MEALS;

-- Q4. WHICH VOLUNTEERS ARE FREE IN A GIVEN ZONE? (ZONE 1 = ANDHERI WEST)
SELECT V.VOLUNTEER_ID, V.FULL_NAME, V.VEHICLE_TYPE, V.PHONE
FROM   VOLUNTEERS V
WHERE  V.ZONE_ID = 1
  AND  V.IS_AVAILABLE = 1;

-- Q5. WHICH CLAIMED FOOD HAS NOT BEEN PICKED UP YET?
SELECT C.CLAIM_ID, B.TITLE, N.ORG_NAME AS NGO, B.EXPIRY_TIME,
       ROUND((B.EXPIRY_TIME - SYSDATE) * 24 * 60) AS MINUTES_LEFT
FROM   CLAIMS C
       JOIN FOOD_BATCHES B ON B.BATCH_ID = C.BATCH_ID
       JOIN NGOS N         ON N.NGO_ID   = C.NGO_ID
WHERE  C.CLAIM_STATUS = 'CLAIMED';

-- =====================================================================
--  PART B: ANALYTICAL QUERIES (THE "INSIGHT" LAYER)
-- =====================================================================

-- Q6. BATCHES AND MEALS BY STATUS (POSTED VS DELIVERED VS EXPIRED ...)
SELECT STATUS, COUNT(*) AS BATCHES, SUM(QUANTITY_MEALS) AS MEALS
FROM   FOOD_BATCHES
GROUP BY STATUS
ORDER BY BATCHES DESC;

-- Q7. MEALS RESCUED VS WASTED PER DONOR, WITH PERCENT EXPIRED
SELECT D.ORG_NAME,
       COUNT(B.BATCH_ID) AS BATCHES_POSTED,
       SUM(CASE WHEN B.STATUS = 'DELIVERED' THEN B.QUANTITY_MEALS ELSE 0 END) AS MEALS_RESCUED,
       SUM(CASE WHEN B.STATUS = 'EXPIRED'   THEN B.QUANTITY_MEALS ELSE 0 END) AS MEALS_WASTED,
       ROUND(100 * SUM(CASE WHEN B.STATUS = 'EXPIRED' THEN 1 ELSE 0 END)
                 / COUNT(B.BATCH_ID), 1) AS PERCENT_EXPIRED
FROM   DONORS D
       JOIN FOOD_BATCHES B ON B.DONOR_ID = D.DONOR_ID
GROUP BY D.ORG_NAME
ORDER BY MEALS_WASTED DESC;

-- Q8. WHICH TYPE OF DONOR WASTES THE MOST FOOD?
SELECT D.DONOR_TYPE,
       COUNT(B.BATCH_ID) AS BATCHES,
       ROUND(100 * SUM(CASE WHEN B.STATUS = 'EXPIRED' THEN 1 ELSE 0 END)
                 / COUNT(B.BATCH_ID), 1) AS PERCENT_EXPIRED
FROM   DONORS D
       JOIN FOOD_BATCHES B ON B.DONOR_ID = D.DONOR_ID
GROUP BY D.DONOR_TYPE
ORDER BY PERCENT_EXPIRED DESC;

-- Q9. AVERAGE HOURS FROM FOOD BEING PREPARED TO AN NGO CLAIMING IT
SELECT ROUND(AVG((C.CLAIMED_AT - B.PREPARED_AT) * 24), 1) AS AVG_HOURS_TO_CLAIM
FROM   CLAIMS C
       JOIN FOOD_BATCHES B ON B.BATCH_ID = C.BATCH_ID;

-- Q10. HOW RELIABLE IS EACH NGO? (USES VIEW 2)
SELECT * FROM V_NGO_PERFORMANCE ORDER BY NO_SHOW_PERCENT DESC;

-- Q11. WHICH ZONES HAVE DONORS BUT NO VERIFIED NGO? (UNDERSERVED AREAS)
SELECT Z.ZONE_NAME
FROM   ZONES Z
WHERE  Z.ZONE_ID IN (SELECT ZONE_ID FROM DONORS)
  AND  Z.ZONE_ID NOT IN (SELECT ZONE_ID FROM NGOS WHERE VERIFICATION_STATUS = 'VERIFIED');

-- =====================================================================
--  PART C: ACCOUNTABILITY AND FOOD SAFETY
-- =====================================================================

-- Q12. WHICH DELIVERIES WERE REJECTED, AND WHY? (DONOR, NGO, REASON)
SELECT DL.DELIVERY_ID, B.TITLE, D.ORG_NAME AS DONOR, N.ORG_NAME AS NGO,
       DL.REJECTION_REASON
FROM   DELIVERIES DL
       JOIN PICKUPS P      ON P.PICKUP_ID = DL.PICKUP_ID
       JOIN CLAIMS C       ON C.CLAIM_ID  = P.CLAIM_ID
       JOIN FOOD_BATCHES B ON B.BATCH_ID  = C.BATCH_ID
       JOIN DONORS D       ON D.DONOR_ID  = B.DONOR_ID
       JOIN NGOS N         ON N.NGO_ID    = C.NGO_ID
WHERE  DL.DELIVERY_STATUS = 'REJECTED';

-- Q13. WHICH DONORS HAVE HAD A SAFETY ISSUE REPORTED?
SELECT DISTINCT D.ORG_NAME
FROM   FEEDBACK F
       JOIN DELIVERIES DL  ON DL.DELIVERY_ID = F.DELIVERY_ID
       JOIN PICKUPS P      ON P.PICKUP_ID    = DL.PICKUP_ID
       JOIN CLAIMS C       ON C.CLAIM_ID     = P.CLAIM_ID
       JOIN FOOD_BATCHES B ON B.BATCH_ID     = C.BATCH_ID
       JOIN DONORS D       ON D.DONOR_ID     = B.DONOR_ID
WHERE  F.SAFETY_ISSUE_REPORTED = 1;

-- Q14. TRACE ONE BATCH FROM KITCHEN TO PLATE (BATCH 1)
SELECT B.TITLE AS FOOD, D.ORG_NAME AS DONOR, N.ORG_NAME AS NGO,
       V.FULL_NAME AS VOLUNTEER, P.PICKED_UP_AT, DL.DELIVERED_AT, DL.MEALS_RECEIVED
FROM   FOOD_BATCHES B
       JOIN DONORS D      ON D.DONOR_ID     = B.DONOR_ID
       JOIN CLAIMS C      ON C.BATCH_ID     = B.BATCH_ID
       JOIN NGOS N        ON N.NGO_ID       = C.NGO_ID
       JOIN PICKUPS P     ON P.CLAIM_ID     = C.CLAIM_ID
       JOIN VOLUNTEERS V  ON V.VOLUNTEER_ID = P.VOLUNTEER_ID
       JOIN DELIVERIES DL ON DL.PICKUP_ID   = P.PICKUP_ID
WHERE  B.BATCH_ID = 1;

